def cluster_colors(n: int) -> list[str]:
    pal = CONFIG["PALETTE"]
    return [pal[i % len(pal)] for i in range(n)]


# Candidate label offsets in points, tried in order: centred, then a ring.
_OFFSETS = [(0, 0), (0, 7), (0, -7), (8, 0), (-8, 0), (7, 5), (-7, 5),
            (7, -5), (-7, -5), (0, 12), (0, -12), (13, 0), (-13, 0)]


def place_labels(ax, xy, texts, priority=None, fontsize=5.2, color="black",
                 leader_from=None, avoid_center=False, occupied=None, **kw):
    """Annotate points, nudging labels off each other and drawing leader lines.

    Greedy: high-priority labels claim their preferred slot first, later ones
    take the nearest free ring position. Overlap is tested on real rendered
    extents, so it is exact rather than an estimate from string length.

    Pass the returned `occupied` list into a later call to keep successive label
    sets from colliding with each other.
    """
    fig = ax.figure
    order = (range(len(texts)) if priority is None
             else sorted(range(len(texts)), key=lambda i: -priority[i]))
    arts = []
    placed = occupied if occupied is not None else []
    fig.canvas.draw()
    rend = fig.canvas.get_renderer()

    # avoid_center keeps a label off its own marker (used where the marker
    # itself carries meaning, e.g. the code triangles on the CA map).
    offsets = _OFFSETS[1:] if avoid_center else _OFFSETS
    for i in order:
        x, y = xy[i]
        best, best_bb, best_pen = offsets[0], None, None
        for off in offsets:
            t = ax.annotate(texts[i], (x, y), textcoords="offset points", xytext=off,
                            fontsize=fontsize, ha="center", va="center", color=color,
                            **kw)
            bb = t.get_window_extent(rend)
            pen = sum(bb.overlaps(p) for p in placed) * 100 + abs(off[0]) + abs(off[1])
            t.remove()
            if best_pen is None or pen < best_pen:
                best, best_bb, best_pen = off, bb, pen
            if pen < 100:      # first collision-free slot wins; ring is ordered
                break
        t = ax.annotate(texts[i], (x, y), textcoords="offset points", xytext=best,
                        fontsize=fontsize, ha="center", va="center", color=color, **kw)
        placed.append(best_bb)
        arts.append(t)
        if leader_from is not None and (abs(best[0]) + abs(best[1])) >= 12:
            t.set_arrowprops = None
            ax.annotate("", xy=(x, y), xytext=best, textcoords="offset points",
                        arrowprops=dict(arrowstyle="-", lw=0.4,
                                        color=leader_from, shrinkA=0, shrinkB=0))
    return placed


