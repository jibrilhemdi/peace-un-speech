class DecisionLog:
    """Collects every judgment call so report.md can be assembled at the end."""

    def __init__(self) -> None:
        self.entries: list[dict] = []

    def log(self, section: str, decision: str, rationale: str = "") -> None:
        self.entries.append(
            {"section": section, "decision": decision, "rationale": rationale}
        )
        print(f"  [decision:{section}] {decision}")

    def to_markdown(self, section: str | None = None) -> str:
        rows = [e for e in self.entries if section is None or e["section"] == section]
        out = []
        for e in rows:
            line = f"- **{e['section']}** — {e['decision']}"
            if e["rationale"]:
                line += f"\n  <br>*Rationale:* {e['rationale']}"
            out.append(line)
        return "\n".join(out)


LOG = DecisionLog()


# -------------------------------------------------------------------- LaTeX --

_LATEX_MAP = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def latex_escape(s) -> str:
    """Escape LaTeX specials and fold non-ASCII typography to safe ASCII."""
    if s is None or (isinstance(s, float) and pd.isna(s)):
        return ""
    s = str(s)
    s = (s.replace("’", "'").replace("‘", "'")
          .replace("“", "``").replace("”", "''")
          .replace("–", "--").replace("—", "---")
          .replace("…", "..."))
    # Fold remaining accents (Turkiye, Mozambique names, etc.) to ASCII.
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.encode("ascii", "replace").decode("ascii")
    return "".join(_LATEX_MAP.get(c, c) for c in s)


def write_table(
    df: pd.DataFrame,
    filename: str,
    caption: str,
    label: str,
    notes: str = "",
    align: str | None = None,
    index: bool = False,
    float_fmt: str = "{:.3f}",
    panel_col: str | None = None,
) -> Path:
    """Write a booktabs table (no vertical rules) with caption, label and notes.

    `panel_col` groups rows into labelled panels (Panel A, Panel B, ...) and drops
    the grouping column from the body.
    """
    d = df.reset_index() if index else df.copy()
    panels = None
    if panel_col and panel_col in d.columns:
        panels = list(dict.fromkeys(d[panel_col]))
        groups = {p: d[d[panel_col] == p].drop(columns=[panel_col]) for p in panels}
        d = d.drop(columns=[panel_col])

    def _row(row):
        cells = []
        for v in row:
            if isinstance(v, float) and pd.notna(v):
                cells.append(float_fmt.format(v))
            else:
                cells.append(latex_escape(v))
        return " & ".join(cells) + r" \\"

    body = []
    if panels is None:
        body = [_row(r) for _, r in d.iterrows()]
    else:
        for i, p in enumerate(panels):
            if i:
                body.append(r"\addlinespace[2pt]")
            body.append(
                rf"\multicolumn{{{len(d.columns)}}}{{l}}{{\textbf{{Panel "
                rf"{chr(65 + i)}: {latex_escape(p)}}}}} \\")
            body.append(r"\addlinespace[1pt]")
            body += [_row(r) for _, r in groups[p].iterrows()]

    if align is None:
        align = "".join(
            "r" if pd.api.types.is_numeric_dtype(d[c]) else "l" for c in d.columns
        )
    header = " & ".join(rf"\textbf{{{latex_escape(c)}}}" for c in d.columns) + r" \\"

    ncol = len(d.columns)
    # Wide tables get a smaller body and tighter column separation so they still
    # fit the text block of a portrait page without \resizebox.
    size = r"\footnotesize" if ncol >= 8 else r"\small"
    lines = [
        r"% Auto-generated by analysis.pipeline -- do not edit by hand.",
        r"\begin{table}[htbp]",
        r"\centering",
        rf"\caption{{{latex_escape(caption)}}}",
        rf"\label{{{label}}}",
        size,
    ]
    if ncol >= 8:
        lines.append(r"\setlength{\tabcolsep}{3.5pt}")
    # Shrink to the text block only when the natural width exceeds it, so a table
    # that already fits is never blown up. Applied to every table so that adding
    # an outcome, cluster or phase to CONFIG can never push one off the page.
    # Requires graphicx.
    lines.append(r"\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%")
    lines += [
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        header,
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    lines.append(r"}")
    if notes:
        lines += [
            r"\begin{minipage}{\textwidth}\vspace{2mm}\footnotesize",
            latex_escape(notes),
            r"\end{minipage}",
        ]
    lines += [r"\end{table}", ""]

    path = OUT_TABLES / filename
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {path.relative_to(path.parents[2])}  ({len(d)} rows x {ncol} cols)")
    return path


def write_data(df: pd.DataFrame, filename: str, index: bool = False) -> Path:
    path = OUT_DATA / filename
    df.to_csv(path, index=index, encoding="utf-8")
    print(f"  wrote {path.relative_to(path.parents[2])}  ({len(df)} rows)")
    return path


