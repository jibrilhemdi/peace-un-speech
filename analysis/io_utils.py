def _norm_country(name: str) -> str:
    s = str(name).replace("’", "'").strip()
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if not unicodedata.combining(c))


def iso3(name: str) -> str:
    """ISO3 code for a UN country name; falls back to a 3-letter stub."""
    key = _norm_country(name)
    if key in ISO3:
        return ISO3[key]
    stub = re.sub(r"[^A-Za-z]", "", key).upper()[:3]
    return stub or "UNK"


